/**
 * Optional LLM Logic Explainer
 * MICROCODE INSPECTOR
 *
 * Provides optional explanation assistance for reconstructed logic.
 *
 * Strict Non-Negotiable Standards:
 * 1. 100% Opt-In: Disabled by default. Zero calls without explicit user consent.
 * 2. Full Disclosure: Explicitly discloses what disassembly text is sent and to where.
 * 3. Never uploads raw binary firmware dumps.
 * 4. Local Credential Redaction: High-entropy tokens, passwords, and API keys are redacted before transmission.
 * 5. Local-Only Mode: Local deterministic template synthesis available without any network calls.
 * 6. Model output is strictly tagged as an unverified hypothesis, not ground truth.
 */

import type { FunctionBoundary } from '../types.ts';
import { formatHexAddress } from '../../utils/address.ts';

export interface LlmExplanationRequest {
  optInConfirmed: boolean;
  mode: 'local_only' | 'custom_endpoint';
  endpointUrl?: string;
  apiKey?: string;
  modelName?: string;
}

export interface LlmExplanationResult {
  isOptedIn: boolean;
  provider: string;
  disclosedPayload: string;
  redactedSecretsCount: number;
  explanationText: string;
  isHypothesis: boolean;
  hypothesisNotice: string;
  warning?: string;
}

export class OptionalLlmExplainer {
  public static readonly HYPOTHESIS_NOTICE =
    'UNVERIFIED AI HYPOTHESIS: The following high-level summary was generated by an AI model. ' +
    'It does not constitute mathematical proof or ground truth. Assembly instructions and hardware register facts remain the sole ground truth.';

  public static readonly DATA_DISCLOSURE_NOTICE =
    'DATA DISCLOSURE: Only sanitized assembly instruction mnemonics, synthetic names, and peripheral register facts ' +
    'are included in this payload. Raw firmware binary dumps are NEVER transmitted. Likely credentials and high-entropy secrets are automatically redacted locally.';

  /**
   * Scans text for Wi-Fi passwords, bearer tokens, API keys, and high-entropy strings,
   * replacing them with [REDACTED_CREDENTIAL].
   */
  public static redactCredentials(text: string): { redactedText: string; redactionCount: number } {
    let count = 0;

    // Pattern 1: Common credential key-value pairs (password=..., key=..., secret=...)
    const credRegex = /(password|passwd|pwd|secret|token|api_key|apikey|bearer)\s*[:=]\s*["']?([A-Za-z0-9_\-.~!@#$%^&*]{6,})["']?/gi;
    let redacted = text.replace(credRegex, (match, prefix) => {
      count++;
      return `${prefix}=[REDACTED_CREDENTIAL]`;
    });

    // Pattern 2: Bearer auth tokens
    const bearerRegex = /bearer\s+([A-Za-z0-9_\-.~+/]{12,})/gi;
    redacted = redacted.replace(bearerRegex, () => {
      count++;
      return 'Bearer [REDACTED_TOKEN]';
    });

    // Pattern 3: Private key blocks
    const keyRegex = /-----BEGIN[ A-Z0-9_-]+PRIVATE KEY-----[^-]+-----END[ A-Z0-9_-]+PRIVATE KEY-----/g;
    redacted = redacted.replace(keyRegex, () => {
      count++;
      return '[REDACTED_PRIVATE_KEY_BLOCK]';
    });

    return { redactedText: redacted, redactionCount: count };
  }

  /**
   * Formats the exact text payload that would be inspected or transmitted.
   */
  public static prepareDisclosedPayload(fn: FunctionBoundary): string {
    const lines: string[] = [];
    lines.push(`Function: ${fn.name} (${formatHexAddress(fn.entryAddress, 6)} - ${formatHexAddress(fn.endAddress, 6)})`);
    lines.push(`Confidence: ${fn.confidence} (Score: ${fn.confidenceScore})`);

    if (fn.peripheralAccesses.length > 0) {
      lines.push('Confirmed Peripheral Hardware Accesses:');
      for (const p of fn.peripheralAccesses) {
        lines.push(`  - ${p.confirmedFact}`);
      }
    }

    if (fn.loopPatterns.length > 0) {
      lines.push('Detected Loop Patterns:');
      for (const l of fn.loopPatterns) {
        lines.push(`  - ${l.kind}: ${l.confidenceReason}`);
      }
    }

    lines.push('Assembly Instructions (Address / Opcode / Mnemonic / Operands):');
    for (const b of fn.basicBlocks) {
      for (const i of b.instructions) {
        lines.push(`  ${formatHexAddress(i.address, 4)}: ${i.mnemonic} ${i.operands}`);
      }
    }

    return lines.join('\n');
  }

  /**
   * Generates logic explanation respecting opt-in and local-only safeguards.
   */
  public static async explain(
    fn: FunctionBoundary,
    request: LlmExplanationRequest
  ): Promise<LlmExplanationResult> {
    if (!request.optInConfirmed) {
      return {
        isOptedIn: false,
        provider: 'None (Opt-in required)',
        disclosedPayload: '',
        redactedSecretsCount: 0,
        explanationText: 'LLM explanation is disabled by default. Enable opt-in in the Pseudocode Inspector to activate.',
        isHypothesis: true,
        hypothesisNotice: this.HYPOTHESIS_NOTICE,
        warning: 'User has not opted in to LLM explanation.',
      };
    }

    // 1. Prepare minimal instruction text (no binary bytes)
    const rawPayload = this.prepareDisclosedPayload(fn);

    // 2. Local secret redaction
    const { redactedText, redactionCount } = this.redactCredentials(rawPayload);

    // 3. Mode execution
    if (request.mode === 'local_only' || !request.endpointUrl) {
      // Deterministic local template synthesis (no network calls)
      const summaryLines: string[] = [];
      summaryLines.push(`### Reconstructed Logic Hypothesis for ${fn.name}`);
      summaryLines.push('');
      summaryLines.push(`**Function Role**: Subroutine starting at ${formatHexAddress(fn.entryAddress, 6)} containing ${fn.instructionCount} instructions across ${fn.basicBlocks.length} basic block(s).`);

      if (fn.peripheralAccesses.length > 0) {
        summaryLines.push('');
        summaryLines.push('**Hardware Interaction**:');
        for (const p of fn.peripheralAccesses) {
          summaryLines.push(`* ${p.registerName}: ${p.inferredMeaning}`);
        }
      }

      if (fn.loopPatterns.length > 0) {
        summaryLines.push('');
        summaryLines.push('**Control Flow**:');
        for (const l of fn.loopPatterns) {
          summaryLines.push(`* ${l.kind.replace('_', ' ').toUpperCase()}: ${l.confidenceReason}`);
        }
      }

      summaryLines.push('');
      summaryLines.push('**Traceable Assembly Ground Truth**: Refer to side-by-side assembly mappings for instruction-level verification.');

      return {
        isOptedIn: true,
        provider: 'Local Rule-Based Synthesizer (Local-Only, No Network)',
        disclosedPayload: redactedText,
        redactedSecretsCount: redactionCount,
        explanationText: summaryLines.join('\n'),
        isHypothesis: true,
        hypothesisNotice: this.HYPOTHESIS_NOTICE,
      };
    }

    // Custom external endpoint if user provided one
    try {
      const response = await fetch(request.endpointUrl, {
        method: 'POST',
        headers: {
          'Content-Type': 'application/json',
          ...(request.apiKey ? { Authorization: `Bearer ${request.apiKey}` } : {}),
        },
        body: JSON.stringify({
          prompt: `Analyze the following microcontroller disassembly and explain the approximate program logic. Treat as a hypothesis:\n\n${redactedText}`,
          model: request.modelName || 'default',
        }),
      });

      if (!response.ok) {
        throw new Error(`Endpoint returned HTTP ${response.status}: ${response.statusText}`);
      }

      const data = await response.json();
      const outputText = data.text || data.choices?.[0]?.message?.content || JSON.stringify(data);

      return {
        isOptedIn: true,
        provider: `Custom Endpoint (${request.endpointUrl})`,
        disclosedPayload: redactedText,
        redactedSecretsCount: redactionCount,
        explanationText: outputText,
        isHypothesis: true,
        hypothesisNotice: this.HYPOTHESIS_NOTICE,
      };
    } catch (err: unknown) {
      const message = err instanceof Error ? err.message : String(err);
      return {
        isOptedIn: true,
        provider: `Custom Endpoint (${request.endpointUrl})`,
        disclosedPayload: redactedText,
        redactedSecretsCount: redactionCount,
        explanationText: `Failed to query custom endpoint: ${message}`,
        isHypothesis: true,
        hypothesisNotice: this.HYPOTHESIS_NOTICE,
        warning: message,
      };
    }
  }
}
